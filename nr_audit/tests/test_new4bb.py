"""NEW-4bb（N56）：第 7 章按外部意见的核对结论逐句改准；不改定理类陈述、表值、宏与图件。"""
from conftest import SRC

ROOT = SRC.ROOT


def text(rel):
    return (ROOT / rel).read_text(encoding='utf-8')


def test_ch7_wording():
    xt = text('paper/sections/07_xian.tex')
    s72, s73 = xt.split('\\subsection{控制组合}')[1].split('\\subsection{与实际干预的对照}')
    for s in (
        '本节计算西安参数下阈值策略所需的干预强度、控制时长与涉及的人数',
        '先用 TDINN 方法从西安的病例数据推断接触率与隔离比例的时间序列，再用参数化函数拟合这些序列',
        '本文只用最小二乘估计初始感染人数 $I_0$',
        '沿用 He 等的病例对应方式',
        '仅隔离控制与成本最优控制的启动时刻',
        '日新增病例与模型拟合结果',
        '控制时长远长于基准算例，原因是设计阈值只占人口的 $0.1\\%$',
        '仅隔离控制到清零时间的总累计新增感染减少约',
        '仅减少接触仍保留常规的追踪隔离',
        '启动时的易感者人数 $S^*$ 大于 $S_{\\rm sw}$',
        '后段接触率相对 $c_0$ 的最大降幅约为 $28.2\\%$',
        '仅隔离段消失的权重还取决于启动时的易感者人数 $S^*$',
        '黑色数字标注等高线的 $y$ 值',
        '(b) 归一化接触率 $c_c^*/c_0$',
        'TDINN 控制是从病例数据重构的干预',
        '强度高、清零快',
        '接触率的降幅趋向约 $73\\%$',
        '在清零前达到的水平',
        '阈值策略每日追踪隔离的人数至少是 TDINN 的 $15$ 倍，并要维持整个阈值控制期',
        '若清零后释放全部隔离易感者',
        '散点为观测累计病例数',
        # 保留的内容
        '$R_c\\approx4.43$', '不把感染维持在某一阈值，也不要求在某一状态退出', 'TDINN 与阈值策略完成的任务不同',
        '多出的感染换来的是退出后的状态', '这一下界是在 $S_c$ 退出必须付出的感染',
        '$2.74\\times10^6$ 人降到约 $2.16\\times10^6$ 人', '约 $8.04\\times10^6$ 人', '$1.38\\times10^6$ 人',
        '两类策略的差别因而不只在强度，更在要维持多久、涉及多少人', '清零约需 $389$ d',
    ):
        assert s in xt, s
    for gone in ('意味着什么', '本文采用其表 3 中西安的结果', '各控制的排序由定理', '约 $6.55\\times10^6$',
                 '介于两种单控制之间，成本则最低', '启动状态 $S^*$', '$5.06$ 倍', '基准算例中这三个值',
                 '黑色数字为等值', '实际采取的干预', '持续短', '随易感者减少而放松，但', '足以实施阈值策略',
                 '不是对真实政策年限的预测', '观测累计量', '在 $I$ 首次达到 $\\eta$ 时启动'):
        assert gone not in xt, gone
    # 工作量单独成段，15 倍只写一次
    assert xt.count('至少是 TDINN 的 $15$ 倍') == 1 and '\n\n工作量则相差很大' in s73
    # 第 7.2 节保留单控制的放松（对单控制成立），第 7.3 节不再泛指
    assert '此后两者都随易感者减少而放松' in s72
    # 表值不变
    for v in ('621.97 & 840.66', '170.63 & 389.32', '218.10 & 436.79', '& 5.06\\\\'):
        assert v in xt, v
    s6 = text('paper/supplement_sections/S6_xian.tex')
    assert '的下界一致：降低阈值不能把感染降到下界以下' in s6 and '据此说明' not in s6
