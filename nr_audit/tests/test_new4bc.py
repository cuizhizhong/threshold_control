        '两种干预仍有不同的组合方式',
        '此后可一直保持常规控制、且非隔离感染者人数不再超过阈值的最早时刻',
        '退出后 $I$ 不再上升',
        '在仅隔离控制下，从启动到清零',
        '清零时的累计新增感染接近总易感者 $S+S_q$ 从初值降到 $S_c$ 所需的人数',
